create table if not exists public.volunteer_applications (
  id bigint generated by default as identity constraint applications_pkey primary key,
  created_at timestamptz not null default now(),
  full_name text,
  email text,
  phone text,
  position text,
  availability jsonb,
  experience_summary text,
  causes text,
  preferred_name text,
  location text,
  linkedin_url text,
  start_date date,
  time_constraints text,
  education text,
  strengths text,
  tools text,
  resume_link text,
  inspiration text,
  work_auth text,
  sponsorship text,
  consent boolean,
  submitted_at timestamptz default now(),
  resume_file_path text,
  resume_file_name text,
  resume_file_type text,
  resume_file_size integer,
  submitted_ip text,
  initial_hr_email_queued_at timestamptz,
  initial_hr_email_sent_at timestamptz,
  recruitment_status text not null default 'new_application',
  idempotency_key text,
  application_language text,
  constraint volunteer_applications_language_check
    check (application_language is null or application_language = any(array['en','fr','es','ar']))
);

create index if not exists volunteer_applications_submitted_at_idx
  on public.volunteer_applications(submitted_at desc);
create unique index if not exists volunteer_applications_idempotency_unique
  on public.volunteer_applications(idempotency_key)
  where idempotency_key is not null;

create table if not exists public.hr_email_outbox (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  application_id bigint not null references public.volunteer_applications(id),
  recipient_name text not null,
  recipient_email text not null,
  position text,
  email_type text not null default 'initial_volunteer_acknowledgment',
  subject text not null,
  body text not null,
  status text not null default 'pending'
    check (status in ('pending','processing','sent','failed','skipped')),
  sent_at timestamptz,
  sent_by text,
  external_message_id text,
  error_message text,
  attempts integer not null default 0,
  last_attempt_at timestamptz,
  unique(application_id,email_type)
);
create index if not exists idx_hr_email_outbox_application
  on public.hr_email_outbox(application_id);
create index if not exists idx_hr_email_outbox_status_created
  on public.hr_email_outbox(status,created_at);

-- The historical view existed before July 17 security hardening required it.
create or replace view public.pending_hr_volunteer_emails
with (security_invoker=true)
as
  select o.id outbox_id,o.created_at,o.application_id,
         o.recipient_name,o.recipient_email,o.position,o.subject,
         o.email_type,o.status,o.attempts,
         v.preferred_name,v.location,v.start_date,v.education,v.strengths,v.tools
  from public.hr_email_outbox o
  join public.volunteer_applications v on v.id=o.application_id
  where o.status='pending'
  order by o.created_at;

alter table public.volunteer_applications enable row level security;
alter table public.hr_email_outbox enable row level security;
revoke all on public.volunteer_applications,public.hr_email_outbox
  from public,anon,authenticated;
revoke all on public.pending_hr_volunteer_emails from public,anon,authenticated;
grant all on public.volunteer_applications,public.hr_email_outbox to service_role;
grant select on public.pending_hr_volunteer_emails to service_role;
